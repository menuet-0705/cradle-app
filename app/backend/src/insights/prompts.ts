/**
 * 記録を JSON にして <data> で囲む。利用者が入力した文字列に </data> などが含まれても
 * 囲みを抜け出せないよう、< > & を \uXXXX にエスケープする（JSON としての値は変わらない）
 */
function dataBlock(input: unknown): string {
  const json = JSON.stringify(input, null, 1).replace(
    /[<>&]/g,
    (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`,
  );
  return `<data>\n${json}\n</data>`;
}

/** 記録はデータであることが分かるよう、タグで囲んで渡す */
export function mealSuggestionUserMessage(input: MealSuggestionInput): string {
  return `次の記録をもとに、次の食事（${input.nextMeal}）の献立を提案してください。

${dataBlock(input)}`;
}

export function weeklyReportUserMessage(input: WeeklyReportInput): string {
  return `次の 1 週間の記録をもとに、ふりかえりのレポートを書いてください。

${dataBlock(input)}`;
}
